package rabbitmq

import (
	"context"
	"encoding/json"
	"fmt"
	"log/slog"
	"sync"

	amqp "github.com/rabbitmq/amqp091-go"
)

// MessageHandler is the callback invoked for every consumed message.
// Return nil to ACK; return an error to NACK with requeue.
type MessageHandler func(ctx context.Context, body []byte) error

// Consumer receives messages from a RabbitMQ queue using a worker pool.
type Consumer struct {
	rmq         *RabbitMQ
	queueName   string
	workerCount int
	autoAck     bool
	handler     MessageHandler
}

// ConsumerOptions configures a Consumer.
type ConsumerOptions struct {
	// QueueName is the name of the queue to consume from.
	QueueName string

	// WorkerCount is the number of concurrent goroutine workers (default: 5).
	WorkerCount int

	// AutoAck enables automatic message acknowledgement.
	// When false (recommended), the handler must succeed for the message to be ACKed.
	AutoAck bool
}

// NewConsumer creates a Consumer with the given options and message handler.
func NewConsumer(rmq *RabbitMQ, opts ConsumerOptions, handler MessageHandler) *Consumer {
	if opts.WorkerCount == 0 {
		opts.WorkerCount = 5
	}
	return &Consumer{
		rmq:         rmq,
		queueName:   opts.QueueName,
		workerCount: opts.WorkerCount,
		autoAck:     opts.AutoAck,
		handler:     handler,
	}
}

// DeclareQueue create queue if not exists
func (c *Consumer) DeclareQueue(durable, autoDelete bool) error {
	ch, err := c.rmq.GetChannel()
	if err != nil {
		return err
	}
	_, err = ch.QueueDeclare(
		c.queueName, // name
		durable,     // durable
		autoDelete,  // delete when unused
		false,       // exclusive
		false,       // no-wait
		nil,         // arguments
	)
	return err
}

// BindQueue bind queue to exchange with routing key
func (c *Consumer) BindQueue(exchange, routingKey string) error {
	ch, err := c.rmq.GetChannel()
	if err != nil {
		return err
	}
	return ch.QueueBind(
		c.queueName, // queue name
		routingKey,  // routing key
		exchange,    // exchange
		false,       // no-wait
		nil,         // args
	)
}

// Start start consume messages with worker pool
func (c *Consumer) Start(ctx context.Context) error {
	ch, err := c.rmq.GetChannel()
	if err != nil {
		return err
	}
	// Register consumer
	msgs, err := ch.Consume(
		c.queueName, // queue
		"",          // consumer tag (auto-generated by broker)
		c.autoAck,   // auto-ack (set via ConsumerOptions.AutoAck)
		false,       // exclusive
		false,       // no-local
		false,       // no-wait
		nil,         // args
	)
	if err != nil {
		return fmt.Errorf("failed to register consumer: %w", err)
	}

	slog.InfoContext(ctx, "Consumer started",
		slog.String("queue_name", c.queueName),
		slog.Int("worker_count", c.workerCount),
		slog.Bool("auto_ack", c.autoAck),
	)

	// Create worker pool with  goroutines
	var wg sync.WaitGroup

	// Channel for distribute messages to workers
	jobChan := make(chan amqp.Delivery, c.workerCount*2)

	// Start workers
	for i := 0; i < c.workerCount; i++ {
		wg.Add(1)
		go c.worker(ctx, i, jobChan, &wg)
	}
	// Distribute messages to workers
	go func() {
		for msg := range msgs {
			select {
			case jobChan <- msg:
			case <-ctx.Done():
				return
			}
		}
	}()

	// Wait for context cancellation
	<-ctx.Done()
	slog.Debug("Shutting down consumer...")

	// Close job channel and wait workers done
	close(jobChan)
	wg.Wait()
	slog.Debug("Consumer stopped gracefully")
	return nil
}

// worker goroutine for process messages
func (c *Consumer) worker(ctx context.Context, id int, jobs <-chan amqp.Delivery, wg *sync.WaitGroup) {
	defer wg.Done()
	slog.InfoContext(ctx, "Worker started", slog.Int("worker_id", id))
	for {
		select {
		case msg, ok := <-jobs:
			if !ok {
				slog.InfoContext(ctx, "Worker stopped", slog.Int("worker_id", id))
				return
			}

			// Process message
			err := c.handler(ctx, msg.Body)

			if err != nil {
				slog.ErrorContext(ctx, "Worker : Error processing message",
					slog.Int("worker_id", id),
					slog.Any("error", err),
				)
				// Nack with requeue
				if nackErr := msg.Nack(false, true); nackErr != nil {
					slog.ErrorContext(ctx, "Failed to nack message",
						slog.Int("worker_id", id),
						slog.Any("error", nackErr),
					)
				}
			} else {
				slog.DebugContext(ctx, "Worker : Message processed successfully",
					slog.Int("worker_id", id),
				)
				// Ack message
				if ackErr := msg.Ack(false); ackErr != nil {
					slog.ErrorContext(ctx, "Failed to ack message",
						slog.Int("worker_id", id),
						slog.Any("error", ackErr),
					)
				}
			}
		case <-ctx.Done():
			slog.DebugContext(ctx, "Worker stopping...", slog.Int("worker_id", id))
			return
		}
	}
}

// UnmarshalMessage helper for unmarshal JSON message
func UnmarshalMessage(body []byte, v interface{}) error {
	return json.Unmarshal(body, v)
}
